def split_templates_by_style() -> dict[str, dict[str, list[tuple[str, str]]]]:
    """split -> style -> [(template_id, template_text)] の厳密非交差分割を返す。"""
    out = {"train": {}, "dev": {}, "sealed_v2": {}}
    for st, arr in TEMPLATES_BY_STYLE.items():
        out["train"][st] = [(f"{st}_{i:02d}", arr[i]) for i in range(0, 30)]
        out["dev"][st] = [(f"{st}_{i:02d}", arr[i]) for i in range(30, 40)]
        out["sealed_v2"][st] = [(f"{st}_{i:02d}", arr[i]) for i in range(40, 50)]
    return out


POOL_TARGET_COUNTS = {"train": 8400, "dev": 1000, "sealed_v2": 500}


def build_paragraph_pools(seed: int = 20261119) -> tuple[dict[str, list[dict]], dict]:
    """全 split 用の具体段落プール (8,400 / 1,000 / 500 = 計 9,900本) を構築する。"""
    rng = random.Random(seed)
    tpl_map = split_templates_by_style()
    seen_para_norms = set()
    pools: dict[str, list[dict]] = {}
    uid = 0

    for split_name in ("train", "dev", "sealed_v2"):
        target_n = POOL_TARGET_COUNTS[split_name]
        all_tpls = [
            (st, tid, tmpl)
            for st in STYLES
            for tid, tmpl in tpl_map[split_name][st]
        ]
        n_tpl = len(all_tpls)
        base_per = target_n // n_tpl
        rem = target_n % n_tpl
        order = list(range(n_tpl))
        rng.shuffle(order)

        split_pool = []
        for pos, tidx in enumerate(order):
            st, tid, tmpl = all_tpls[tidx]
            cnt = base_per + (1 if pos < rem else 0)
            made = 0
            attempts = 0
            while made < cnt and attempts < cnt * 30:
                attempts += 1
                uid += 1
                txt = tmpl.format(**_ctx(rng, uid))
                np_txt = _norm_p(txt)
                if np_txt in seen_para_norms:
                    continue
                seen_para_norms.add(np_txt)
                pid = f"{split_name}_p_{len(split_pool):05d}"
                split_pool.append({
                    "pid": pid,
                    "split": split_name,
                    "style": st,
                    "tid": tid,
                    "text": txt,
                    "norm": np_txt,
                })
                made += 1
            assert made == cnt, f"Failed to expand template {tid} for {split_name}: {made}/{cnt}"

        rng.shuffle(split_pool)
        pools[split_name] = split_pool

    n_tr = {x["norm"] for x in pools["train"]}
    n_dv = {x["norm"] for x in pools["dev"]}
    n_sl = {x["norm"] for x in pools["sealed_v2"]}
    assert not (n_tr & n_dv) and not (n_tr & n_sl) and not (n_dv & n_sl)

    pool_meta = {
        "total_base_templates": sum(len(v) for v in TEMPLATES_BY_STYLE.values()),
        "base_templates_by_split": {
            sp: sum(len(tpl_map[sp][st]) for st in STYLES) for sp in ("train", "dev", "sealed_v2")
        },
        "base_templates_by_style_total": {st: len(arr) for st, arr in TEMPLATES_BY_STYLE.items()},
        "concrete_pool_total": sum(len(v) for v in pools.values()),
        "concrete_pool_by_split": {sp: len(v) for sp, v in pools.items()},
        "concrete_pool_by_style": {
            sp: dict(sorted(Counter(x["style"] for x in pools[sp]).items()))
            for sp in ("train", "dev", "sealed_v2")
        },
        "cross_split_paragraph_exact_overlap": {"train_dev": 0, "train_sealed_v2": 0, "dev_sealed_v2": 0},
    }
    return pools, pool_meta


def _format_document(
    rng: random.Random,
    chosen: list[dict],
    doc_style: str,
    is_mixed: bool,
) -> str:
    """選択された段落群を業務文書のフォーマットへ自然に整形する。"""
    dept = rng.choice(DEPTS)
    doc = rng.choice(DOCS)
    tool = rng.choice(TOOLS)
    role = rng.choice(ROLES)
    dt = rng.choice(DATES)
    ver = f"v{rng.randint(1, 4)}.{rng.randint(0, 9)}"
    ref = f"DOC-{rng.randint(1000, 9999)}"
    paras = [c["text"] for c in chosen]
    body = "\n\n".join(paras)

    fmt_choices_by_style = {
        "sop": ["markdown_sop", "wiki", "html", "rag"],
        "report": ["report_header", "mail", "markdown", "json"],
        "notice": ["mail_notice", "notice_banner", "html", "markdown"],
        "minutes": ["minutes_doc", "mail", "markdown", "rag"],
        "policy": ["policy_doc", "wiki", "html", "rag"],
        "faq": ["faq_doc", "wiki", "html", "json"],
        "release": ["release_doc", "mail", "markdown", "html"],
        "proposal": ["proposal_doc", "wiki", "json", "rag"],
    }
    if is_mixed:
        fmt = rng.choice(["mail", "wiki", "rag", "html", "json", "csv"])
    else:
        fmt = rng.choice(fmt_choices_by_style[doc_style])

    if fmt == "markdown_sop":
        txt = f"# 【標準運用手順】{doc}（{ver}）\n- 主管部署：{dept} / 対象ツール：{tool}\n- 更新日：{dt} / 管理番号：{ref}\n\n{body}"
    elif fmt == "report_header":
        txt = f"■業務報告書：{doc}\n発信元：{dept}（{role}）｜作成日：{dt}｜整理番号：{ref}\n\n{body}"
    elif fmt == "mail_notice":
        txt = f"件名：【社内案内】{doc}について（{ref}）\n宛先：関係者各位\n送信元：{dept} {role}\n\nお疲れ様です。{dept}の{role}です。\n\n{body}\n\nよろしくお願いいたします。"
    elif fmt == "notice_banner":
        txt = f"【{dept}からのお知らせ（{dt}）】\n対象：{tool} / 関連文書：{doc} ({ref})\n\n{body}"
    elif fmt == "minutes_doc":
        txt = f"# 会議議事録：{doc}\n- 開催日：{dt}\n- 主管：{dept} / 進行：{role}\n- 管理ID：{ref}\n\n{body}"
    elif fmt == "policy_doc":
        txt = f"■ 社内規程・運用ガイドライン：{doc}（{ver}）\n制定・改訂所管：{dept}（{dt}更新 / {ref}）\n\n{body}"
    elif fmt == "faq_doc":
        txt = f"# よくある質問（FAQ）：{tool}・{doc}\n管理：{dept}（{dt}更新 / {ref}）\n\n{body}"
    elif fmt == "release_doc":
        txt = f"## リリース・保守情報 {ver}（{dt}）\n対象システム：{tool}｜担当：{dept}｜記録ID：{ref}\n\n{body}"
    elif fmt == "proposal_doc":
        txt = f"# 企画・要件概要資料：{doc}（{ver}）\n起案：{dept} {role}｜作成：{dt}｜番号：{ref}\n\n{body}"
    elif fmt == "mail":
        txt = f"件名：{doc}の共有 ({ref})\n本文：\n各位\n\n{dept}の{role}より共有いたします。\n\n{body}\n\nご確認のほどよろしくお願いいたします。"
    elif fmt in ("wiki", "markdown"):
        txt = f"# {doc} ({ver})\n- 部署：{dept}\n- 更新：{dt}\n- ID：{ref}\n\n{body}"
    elif fmt == "rag":
        txt = f"[参照文書チャンク: {ref} | {tool} | {dept}]\n{body}\n[/参照文書チャンク]"
    elif fmt == "html":
        p_tags = "".join(f"<p>{p}</p>" for p in paras)
        txt = f'<article class="internal-doc" data-ref="{ref}"><h2>{doc}</h2><div class="meta">{dept} / {dt} ({ver})</div>{p_tags}</article>'
    elif fmt == "json":
        p_join = " ".join(paras).replace('"', "'").replace("\n", " ")
        txt = f'{{"doc_id": "{ref}", "dept": "{dept}", "title": "{doc}", "version": "{ver}", "updated_at": "{dt}", "content": "{p_join}"}}'
    else:
        p_join = " ".join(paras).replace('"', "'").replace("\n", " ")
        txt = f'id,dept,doc,updated,body\n{ref},{dept},{doc},{dt},"{p_join}"'

    r = rng.random()
    if r < 0.08:
        txt = txt.replace("\n", "\r\n")
    elif r < 0.15:
        txt = txt.replace("：", ": ")
    return txt


def generate_benign_long_split(
    split_name: str,
    n_docs: int,
    pool: list[dict],
    rng: random.Random,
    seen_doc_norms: set[str],
    max_docs_per_para: int = 5,
) -> tuple[list[dict], dict]:
    """段落あたり上限 max_docs_per_para (既定5件) を厳密に守りつつ n_docs 件の benign_long を生成する。"""
    remaining = {p["pid"]: max_docs_per_para for p in pool}
    by_pid = {p["pid"]: p for p in pool}
    by_style = {st: [p["pid"] for p in pool if p["style"] == st] for st in STYLES}
    doc_use_count = Counter()

    k3 = int(round(n_docs * 0.30))
    k4 = int(round(n_docs * 0.40))
    k5 = n_docs - k3 - k4
    k_seq = [3] * k3 + [4] * k4 + [5] * k5
    assert len(k_seq) == n_docs
    total_cap = len(pool) * max_docs_per_para
    assert sum(k_seq) <= total_cap, f"Capacity {total_cap} < needed slots {sum(k_seq)}"
    rng.shuffle(k_seq)

    docs_out = []
    style_doc_counts = Counter()

    for idx_doc, k in enumerate(k_seq):
        is_mixed = (rng.random() < 0.25)
        main_style = STYLES[idx_doc % len(STYLES)]

        chosen_pids = None
        final_txt = None

        for attempt in range(40):
            if not is_mixed and attempt < 20:
                cand_pids = [pid for pid in by_style[main_style] if remaining[pid] > 0]
            else:
                cand_pids = [pid for pid, rem in remaining.items() if rem > 0]

            cand_pids.sort(key=lambda pid: (remaining[pid], rng.random()), reverse=True)

            picked = []
            used_tids = set()
            for pid in cand_pids:
                tid = by_pid[pid]["tid"]
                if tid in used_tids:
                    continue
                picked.append(pid)
                used_tids.add(tid)
                if len(picked) == k:
                    break

            if len(picked) < k:
                all_cands = [pid for pid, rem in remaining.items() if rem > 0 and pid not in picked]
                all_cands.sort(key=lambda pid: (remaining[pid], rng.random()), reverse=True)
                for pid in all_cands:
                    tid = by_pid[pid]["tid"]
                    if tid in used_tids:
                        continue
                    picked.append(pid)
                    used_tids.add(tid)
                    if len(picked) == k:
                        break

            assert len(picked) == k, f"Insufficient remaining paragraphs in {split_name} at doc {idx_doc}: got {len(picked)}/{k}"
            chosen_objs = [by_pid[pid] for pid in picked]
            rng.shuffle(chosen_objs)
            txt = _format_document(rng, chosen_objs, main_style, is_mixed or (len({c["style"] for c in chosen_objs}) > 1))
            nt = _norm_p(txt)
            if nt not in seen_doc_norms:
                seen_doc_norms.add(nt)
                chosen_pids = picked
                final_txt = txt
                break

        assert final_txt is not None and chosen_pids is not None, f"Failed unique doc in {split_name}"
        for pid in chosen_pids:
            remaining[pid] -= 1
            doc_use_count[pid] += 1
            assert doc_use_count[pid] <= max_docs_per_para

        style_key = "mixed" if len({by_pid[pid]["style"] for pid in chosen_pids}) > 1 else main_style
        style_doc_counts[style_key] += 1
        docs_out.append({
            "text": final_txt,
            "label": 0,
            "subcategory": "benign_long",
            "source": "synth_ja_v2",
            "lang": "ja",
        })

    uses_all = [doc_use_count.get(p["pid"], 0) for p in pool]
    max_used = max(uses_all)
    assert max_used <= max_docs_per_para, f"{split_name} exceeded max_docs_per_para: {max_used}"

    uses_sorted = sorted(uses_all)
    hist = dict(sorted(Counter(uses_all).items()))
    stats = {
        "n_docs": len(docs_out),
        "n_gt512chars": sum(1 for d in docs_out if len(d["text"]) > 512),
        "pool_size": len(pool),
        "paragraphs_used_at_least_once": sum(1 for u in uses_all if u > 0),
        "max_docs_per_paragraph_limit": max_docs_per_para,
        "max_docs_per_paragraph_actual": max_used,
        "min_docs_per_paragraph_actual": min(uses_all),
        "mean_docs_per_paragraph": round(sum(uses_all) / len(uses_all), 3),
        "p95_docs_per_paragraph": uses_sorted[int(len(uses_sorted) * 0.95)],
        "usage_histogram": {str(k): v for k, v in hist.items()},
        "doc_style_distribution": dict(sorted(style_doc_counts.items())),
    }
    return docs_out, stats

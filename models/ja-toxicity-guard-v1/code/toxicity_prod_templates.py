def _collect_all_pilot_strings() -> Set[str]:
    """パイロット版テンプレートおよび前後フレーズ文字列の集合を返す。"""
    s: Set[str] = set()
    for splits in pilot_tt.SINGLE_TEMPLATES.values():
        for lst in splits.values():
            s.update(lst)
    for splits in pilot_tt.COOCCUR_TEMPLATES.values():
        for lst in splits.values():
            s.update(lst)
    for splits in pilot_tt.BENIGN_TEMPLATES.values():
        for lst in splits.values():
            s.update(lst)
    for lst in pilot_tt.LEAD_PHRASES.values():
        if lst:
            s.update(x for x in lst if x)
    for lst in pilot_tt.TAIL_PHRASES.values():
        if lst:
            s.update(x for x in lst if x)
    return s


def validate_prod_registry() -> dict:
    """本番テンプレートのID一意性、各分割数、パイロットとの非重複を検証する。"""
    pilot_strs = _collect_all_pilot_strings()
    seen_ids: Set[str] = set()
    prod_strs: Set[str] = set()
    overlap_with_pilot: List[str] = []

    def _reg(tid: str, text: str) -> None:
        assert tid not in seen_ids, f"テンプレートID重複: {tid}"
        seen_ids.add(tid)
        assert text not in prod_strs, f"本番内テンプレート重複 ({tid}): {text}"
        prod_strs.add(text)
        if text in pilot_strs:
            overlap_with_pilot.append(f"{tid}: {text}")

    for label, splits in PROD_SINGLE_TEMPLATES.items():
        assert label in LABELS, f"未知ラベル: {label}"
        for split, min_cnt in (("train", 24), ("dev", 10), ("sealed-test", 10)):
            tpls = splits[split]
            assert len(tpls) >= min_cnt, f"{label}/{split} 不足: {len(tpls)} < {min_cnt}"
            for i, t in enumerate(tpls):
                _reg(f"prod_{split[:2]}_single_{label}_{i:02d}", t)

    for pat, _w in COOCCUR_PATTERNS:
        assert all(lb in LABELS for lb in pat)
        for split, min_cnt in (("train", 8), ("dev", 4), ("sealed-test", 4)):
            tpls = PROD_COOCCUR_TEMPLATES[pat][split]
            assert len(tpls) >= min_cnt, f"{pat}/{split} 不足: {len(tpls)} < {min_cnt}"
            pat_tag = "+".join(pat)
            for i, t in enumerate(tpls):
                _reg(f"prod_{split[:2]}_co_{pat_tag}_{i:02d}", t)

    benign_mins = {
        "criticism": (26, 12, 12),
        "news_quote": (26, 12, 12),
        "debate": (36, 16, 16),
        "support_legal": (18, 10, 10),
        "general": (18, 10, 10),
    }
    for sub, splits in PROD_BENIGN_TEMPLATES.items():
        assert sub in BENIGN_SUBTYPES
        mins = benign_mins[sub]
        for split, min_cnt in zip(("train", "dev", "sealed-test"), mins):
            tpls = splits[split]
            assert len(tpls) >= min_cnt, f"{sub}/{split} 不足: {len(tpls)} < {min_cnt}"
            for i, t in enumerate(tpls):
                _reg(f"prod_{split[:2]}_benign_{sub}_{i:02d}", t)

    for split in ("train", "dev", "sealed-test"):
        for phrase in PROD_LEAD_PHRASES[split]:
            if phrase and phrase in pilot_strs:
                overlap_with_pilot.append(f"lead_{split}: {phrase}")
        for phrase in PROD_TAIL_PHRASES[split]:
            if phrase and phrase in pilot_strs:
                overlap_with_pilot.append(f"tail_{split}: {phrase}")

    assert not overlap_with_pilot, f"パイロット材料との重複検出: {overlap_with_pilot[:5]}"
    return {
        "prod_unique_template_ids": len(seen_ids),
        "prod_unique_template_strings": len(prod_strs),
        "pilot_template_overlap": len(overlap_with_pilot),
    }

